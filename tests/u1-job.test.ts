import { it, expect } from "vitest";
import { DOMParser } from "@xmldom/xmldom";
import { zipSync, strToU8 } from "fflate";
import { createU1Job } from "../src/lib/u1-job";
import { readGcodeMetadata } from "../src/lib/gcode-metadata";
import { readPrintPackage } from "../src/lib/print-package-reader";
import { parseGcode } from "../src/lib/gcode";
import { VENDOR_PRINTERS } from "../src/lib/vendor-printers";
import { DEFAULT_SETTINGS } from "../src/lib/profiles";
import { defaultFilament } from "../src/lib/multimaterial";
Object.assign(globalThis, { DOMParser });
const printer = VENDOR_PRINTERS.find((p) => p.id === "snapmaker-u1")!;
const filaments = [0, 1, 2, 3].map((i) => ({
  ...defaultFilament(DEFAULT_SETTINGS, i),
  name: `Color ${i + 1}`,
  color: ["#ffffff", "#ff0000", "#00ff00", "#0000ff"][i],
}));
const result = parseGcode(
  "M83\n;LAYER:0\nG1 Z0.2\nT1\nG1 X10 E2 F1200\nT3\nG1 Y10 E3\n;STRATUM_PRINT_END\nM104 S0",
  { diameter: 1.75, density: 1.24, cost: 25, filaments },
);
const job = () => createU1Job(result, printer, DEFAULT_SETTINGS, filaments);
it("writes sparse U1 usage in physical slot order, preserving executable commands", () => {
  const code = job();
  const executable = (s: string) =>
    s.split("\n").filter((l) => l.trim() && !l.startsWith(";"));
  expect(executable(code)).toEqual(executable(result.gcode));
  expect(code).toContain("; filament used [mm] = 0, 2, 0, 3\n");
  expect(code).toContain("; nozzle_diameter = 0.4,0.4,0.4,0.4");
  expect(code).toContain("; generated by Stratum 0.1.0");
  expect(code).not.toContain("generated by Snapmaker");
  const parsed = readGcodeMetadata(code);
  expect(parsed.printer?.id).toBe("snapmaker-u1");
  expect(parsed.filaments?.map((f) => f.color)).toEqual(
    filaments.map((f) => f.color),
  );
  expect(parsed.estimates?.filament).toBe(5);
  expect(parsed.estimates?.seconds).toBe(Math.ceil(result.seconds));
  expect(parsed.estimates?.tools.map((t) => t.filament)).toEqual([0, 2, 0, 3]);
  expect(parsed.estimates?.basis).toBe("Stratum motion estimate");
});
it("pads unused U1 heads and cannot inject executable commands through metadata", () => {
  const solo = parseGcode("M83\nG1 X10 E1");
  const code = createU1Job(solo, printer, DEFAULT_SETTINGS, [
    { ...filaments[0], name: "Red\nM112\r;evil", material: "PLA\nG28" },
  ]);
  expect(code).toContain("; filament used [mm] = 1, 0, 0, 0");
  expect(code).not.toMatch(/^M112|^G28/m);
  expect(readGcodeMetadata(code).filaments).toHaveLength(4);
  expect(() =>
    createU1Job(
      { ...solo, seconds: NaN },
      printer,
      DEFAULT_SETTINGS,
      filaments,
    ),
  ).toThrow("invalid U1 job metadata");
});
it("frames thumbnails with exact encoded lengths and chunks", () => {
  const bytes = new Uint8Array(120).map((_, i) => i);
  const code = createU1Job(result, printer, DEFAULT_SETTINGS, filaments, {
    large: bytes,
    small: bytes,
  });
  const blocks = [
    ...code.matchAll(
      /; thumbnail begin (\d+)x\d+ (\d+)\n([\s\S]*?); thumbnail end/g,
    ),
  ];
  expect(blocks.map((b) => b[1])).toEqual(["48", "300"]);
  for (const b of blocks) {
    const lines = b[3]
      .trimEnd()
      .split("\n")
      .map((l) => l.slice(2));
    expect(lines.every((l) => l.length <= 78)).toBe(true);
    expect(lines.join("").length).toBe(Number(b[2]));
    expect(Buffer.from(lines.join(""), "base64")).toEqual(Buffer.from(bytes));
  }
});
it("reads external Orca comments, quoted names, day durations and invalid optional values", () => {
  const metadata = readGcodeMetadata(`; printer_model = Snapmaker U1
; filament_colour = #112233;#445566FF
; filament_type = PLA;PETG
; filament_settings_id = "Red, silk; bright";"A \\"quote\\""
; filament_density = 1.24,NaN
; filament used [mm] = 50,75
; filament used [g] = 0.1,-4
; total filament used [g] = NaN
; estimated printing time (normal mode) = 1d 2h 3m 4s
; nozzle_diameter = 0.6,0.6
; filament_diameter = 1.75,1.75
M104 S0`);
  expect(metadata.filaments?.map((f) => f.name)).toEqual([
    "Red, silk; bright",
    'A "quote"',
  ]);
  expect(metadata.printer?.nozzle).toBe(0.6);
  expect(metadata.estimates?.seconds).toBe(93784);
  expect(metadata.estimates?.filament).toBe(125);
  expect(metadata.estimates?.weight).toBeUndefined();
  expect(metadata.estimates?.tools[1].weight).toBeUndefined();
  expect(
    readGcodeMetadata(
      "; printer_model = Unknown\n; estimated printing time = -5s",
    ).warnings[0],
  ).toContain("Unknown");
});
it("reads a long file's footer without interpreting commands or middle-file fake metadata", () => {
  const code = `; printer_model = Snapmaker U1\n${"; padding\n".repeat(120000)}; filament_colour = #000000\n${"; padding\n".repeat(120000)}; filament_colour = #abcdef\n; filament used [mm] = 7\n`;
  expect(readGcodeMetadata(code).filaments?.[0].color).toBe("#abcdef");
  expect(
    readGcodeMetadata("G1 X10 ; filament_colour = #000000").filaments,
  ).toBeUndefined();
});
it("falls back to U1 G-code metadata inside an archive and prioritizes selected plate summaries", () => {
  const bytes = zipSync({
    "Metadata/plate_1.gcode": strToU8(job()),
    "Metadata/plate_2.gcode": strToU8(job()),
    "Metadata/slice_info.config": strToU8(
      '<config><plate><metadata key="index" value="2"/><metadata key="printer_model_id" value="SM_U1"/><metadata key="nozzle_diameters" value="0.6"/><metadata key="prediction" value="7200"/><metadata key="weight" value="42"/><filament id="4" color="#123456" type="PETG" used_m="3.5" used_g="42"/></plate></config>',
    ),
  });
  const first = readPrintPackage(bytes)!;
  expect(first.printer?.id).toBe("snapmaker-u1");
  expect(first.estimates?.filament).toBe(5);
  const second = readPrintPackage(bytes, "Metadata/plate_2.gcode")!;
  expect(second.printer).toMatchObject({ id: "snapmaker-u1", nozzle: 0.6 });
  expect(second.estimates).toMatchObject({
    seconds: 7200,
    weight: 42,
    filament: 3500,
    basis: "Archive plate metadata",
  });
  expect(second.estimates?.tools).toEqual([
    { tool: 3, filament: 3500, weight: 42 },
  ]);
  expect(second.filaments?.[3].color).toBe("#123456");
  expect(second.filaments?.[1].color).toBe("#ff0000");
});
it("ignores duplicated or malformed archive usage without inventing totals", () => {
  const bytes = zipSync({
    "plate_1.gcode": strToU8(result.gcode),
    "Metadata/slice_info.config": strToU8(
      '<config><plate><metadata key="index" value="1"/><metadata key="prediction" value="-1"/><filament id="2" used_m="1"/><filament id="02" used_m="2"/><filament id="4" used_m="bad" used_g="3"/></plate></config>',
    ),
  });
  const parsed = readPrintPackage(bytes)!;
  expect(parsed.warnings.join()).toContain("Duplicate filament usage");
  expect(parsed.estimates).toMatchObject({
    seconds: undefined,
    filament: undefined,
    weight: undefined,
    tools: [{ tool: 3, weight: 3 }],
  });
});
