import type { Filament, Printer, Settings, SliceResult } from "../types";

const commentValue = (value: string) =>
  value.replace(/[\x00-\x1f\x7f;"\\]/g, " ").slice(0, 200);
const number = (value: number, places = 5) => {
  if (!Number.isFinite(value) || value < 0)
    throw new Error("Cannot export invalid U1 job metadata.");
  return String(Number(value.toFixed(places)));
};
function thumbnail(bytes: Uint8Array, size: number) {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  const data = btoa(binary);
  return [
    `; thumbnail begin ${size}x${size} ${data.length}`,
    ...(data.match(/.{1,78}/g) ?? []).map((line) => `; ${line}`),
    "; thumbnail end",
  ].join("\n");
}
/** U1's published Moonraker reader uses Orca-style comment metadata and PNG blocks. */
export function createU1Job(
  result: SliceResult,
  printer: Printer,
  settings: Settings,
  filaments: Filament[],
  images?: { large: Uint8Array; small: Uint8Array },
): string {
  if (printer.firmware !== "snapmaker-u1" || printer.id !== "snapmaker-u1")
    throw new Error("Select a Snapmaker U1 profile for U1 job metadata.");
  if (
    !filaments.length ||
    filaments.length > 4 ||
    result.tools.some((t) => t.tool < 0 || t.tool >= filaments.length)
  )
    throw new Error("U1 job metadata requires configured tool slots 1–4.");
  const slots = Array.from({ length: 4 }, (_, i) => filaments[i]);
  const values = (get: (f: Filament, i: number) => number, fallback = 0) =>
    slots.map((f, i) => number(f ? get(f, i) : fallback)).join(",");
  const strings = (get: (f: Filament) => string, fallback = "") =>
    slots.map((f) => commentValue(f ? get(f) : fallback)).join(";");
  const usage = (key: "filament" | "weight") =>
    slots
      .map((_, i) => number(result.tools.find((t) => t.tool === i)?.[key] ?? 0))
      .join(", ");
  const summary = [
    `; estimated printing time (normal mode) = ${number(Math.ceil(result.seconds), 0)}s`,
    "; stratum_estimate_basis = motion only; excludes heating, acceleration and firmware macro internals",
    `; filament used [mm] = ${usage("filament")}`,
    `; filament used [g] = ${usage("weight")}`,
    `; total filament used [g] = ${number(result.weight)}`,
    `; total layers count = ${result.layers.length}`,
  ];
  const config = [
    "; CONFIG_BLOCK_START",
    "; printer_model = Snapmaker U1",
    `; printer_settings_id = Snapmaker U1 (${number(printer.nozzle)} nozzle)`,
    "; gcode_flavor = klipper",
    "; print_sequence = by layer",
    "; filament_volume_type = standard,standard,standard,standard",
    `; nozzle_diameter = ${slots.map(() => number(printer.nozzle)).join(",")}`,
    `; filament_diameter = ${slots.map(() => number(printer.filament)).join(",")}`,
    `; filament_colour = ${strings((f) => f.color, "#FFFFFF")}`,
    `; filament_type = ${strings((f) => f.material, "PLA")}`,
    `; filament_settings_id = ${strings((f) => f.name, "Unused")}`,
    `; filament_density = ${values((f) => f.density, 1.24)}`,
    `; filament_cost = ${values((f) => f.cost)}`,
    `; filament_flow_ratio = ${values((f) => f.flow, 1)}`,
    `; filament_max_volumetric_speed = ${values((f) => f.maxFlow)}`,
    `; nozzle_temperature = ${values((f) => f.nozzleTemp)}`,
    `; first_layer_temperature = ${values((f) => f.firstNozzleTemp)}`,
    `; bed_temperature = ${number(settings.bedTemp)}`,
    `; first_layer_bed_temperature = ${number(settings.firstBedTemp)}`,
    `; layer_height = ${number(settings.layerHeight)}`,
    `; first_layer_height = ${number(settings.firstLayerHeight)}`,
    `; line_width = ${number(settings.lineWidth)}`,
    `; outer_wall_speed = ${number(settings.outerSpeed)}`,
    "; CONFIG_BLOCK_END",
  ];
  // The compatibility marker selects Moonraker's metadata decoder without claiming
  // that Snapmaker Orca generated this job or enabling its official-slicer branch.
  return [
    "; HEADER_BLOCK_START",
    "; generated by Stratum 0.1.0",
    "; metadata format: OrcaSlicer Stratum-0.1.0 on export (compatibility marker)",
    ...summary,
    "; HEADER_BLOCK_END",
    ...(images
      ? [thumbnail(images.small, 48), thumbnail(images.large, 300)]
      : []),
    result.gcode.trimEnd(),
    "",
    ...summary,
    ...config,
    "",
  ].join("\n");
}
